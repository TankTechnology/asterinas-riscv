VENDOR = """# generated by u-boot-update
default l0
menu title U-Boot menu
prompt 2
timeout 50
label l0
\tmenu label RockOS normal
\tlinux /vmlinuz-6.6
\tinitrd /initrd.img-6.6
\tfdtdir /dtbs/linux-6.6/
\tappend root=PARTUUID=1234 console=ttyS0,115200 rw

label l0r
\tmenu label rescue
\tlinux /vmlinuz-6.6
"""


def document():
    value = {
        "schema_version": 3,
        "vendor": VENDOR,
        "artifacts": {},
        "desktop_args": (
            menu.BASE_ARGS + " -- --root-init=systemd --debug-console=root"
        ),
    }
    for name in menu.ARTIFACTS:
        payload = name.encode()
        sha = hashlib.sha256(payload).hexdigest()
        value["artifacts"][name] = menu.identity(payload, f"/{name}-{sha[:12]}.bin")
    value["extlinux"] = menu.render(value)
    return value


